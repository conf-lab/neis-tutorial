// scenarioId → 실제 시나리오 (없으면 undefined)
export function getScenarioForLesson(lesson: CurriculumLesson): TutorialScenario | undefined {
  if (!lesson.scenarioId) return undefined;
  return TUTORIAL_SCENARIOS.find((s) => s.id === lesson.scenarioId);
}

const ACCENT_BADGE: Record<CurriculumPhase["accent"], string> = {
  blue: "bg-blue-600 text-white",
  emerald: "bg-emerald-600 text-white",
  amber: "bg-amber-600 text-white",
  violet: "bg-violet-600 text-white",
  rose: "bg-rose-600 text-white",
};

// 인라인 steps를 가진 lesson을 튜토리얼 엔진이 쓰는 TutorialScenario 형태로 변환
export function lessonToScenario(lesson: CurriculumLesson, phase: CurriculumPhase): TutorialScenario {
  const existing = getScenarioForLesson(lesson);
  if (existing) return existing;

  const steps: TutorialStep[] = (lesson.steps || []).map((s, i) => ({
    ...s,
    stepNumber: s.stepNumber ?? i + 1,
    manualPage: s.manualPage ?? lesson.manualPage,
  }));

  return {
    id: `curriculum-${lesson.id}`,
    title: lesson.title,
    category: phase.title,
    badgeColor: ACCENT_BADGE[phase.accent],
    description: lesson.summary,
    relatedManualPage: `매뉴얼 ${lesson.manualPage}p`,
    manualPage: lesson.manualPage,
    steps: steps.length
      ? steps
      : [
          {
            stepNumber: 1,
            title: lesson.title,
            instruction: `${lesson.summary} 자세한 절차는 매뉴얼 ${lesson.manualPage}p를 참고하고, 궁금한 점은 AI 튜터에게 물어보세요.`,
            targetMenuId: lesson.domainId,
            targetSubMenuId: lesson.subMenuId,
            manualPage: lesson.manualPage,
            actionRequired: "NAVIGATE",
          },
        ],
  };
}

export const ALL_LESSONS: { lesson: CurriculumLesson; phase: CurriculumPhase }[] = CURRICULUM.flatMap(
  (phase) => phase.lessons.map((lesson) => ({ lesson, phase }))
);

export const TOTAL_LESSON_COUNT = ALL_LESSONS.length;

export function findLessonEntry(lessonId: string) {
  return ALL_LESSONS.find((e) => e.lesson.id === lessonId);
}

export function nextLessonId(lessonId: string): string | undefined {
  const idx = ALL_LESSONS.findIndex((e) => e.lesson.id === lessonId);
  if (idx < 0 || idx + 1 >= ALL_LESSONS.length) return undefined;
  return ALL_LESSONS[idx + 1].lesson.id;
}
